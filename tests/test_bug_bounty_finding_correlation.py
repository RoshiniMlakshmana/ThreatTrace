# Exact duplicate collapse
# ---------------------------------------------------------------------------


class TestExactDuplicate:
    def test_001_identical_digest_collapsed(self):
        a = _record(evidence_id="EV-a", evidence_digest="sha256:" + "1" * 64)
        b = _record(evidence_id="EV-b", evidence_digest="sha256:" + "1" * 64)  # same digest, different id
        result = correlate_bug_bounty_evidence(evidence_records=[a, b])
        assert result["duplicate_evidence_count"] == 1
        assert result["total_groups"] == 1

    def test_002_distinct_digests_not_collapsed(self):
        a = _record(evidence_id="EV-a", evidence_digest="sha256:" + "1" * 64)
        b = _record(evidence_id="EV-b", evidence_digest="sha256:" + "2" * 64, path="/other", host="other-host")
        result = correlate_bug_bounty_evidence(evidence_records=[a, b])
        assert result["duplicate_evidence_count"] == 0
        assert result["total_groups"] == 2


