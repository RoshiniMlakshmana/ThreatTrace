"""Focused tests for core.bug_bounty_finding_correlation -- the pure,
deterministic multi-tool finding correlator (Block 15G-CD).

No network, filesystem, environment-variable, subprocess, clock,
randomness, database/Supabase, MCP, or LLM/model access occurs anywhere
in this file. Every input is a plain in-memory mapping -- semantic
hints are supplied as already-produced data, never generated by calling
an LLM here.
"""

from __future__ import annotations

import pytest

from core.bug_bounty_evidence_normalization import EVIDENCE_REQUIRED_FIELDS
from core.bug_bounty_finding_correlation import (
    BugBountyFindingCorrelationError,
    correlate_bug_bounty_evidence,
)


def _record(**overrides):
    record = {field: None for field in EVIDENCE_REQUIRED_FIELDS}
    record.update({
        "evidence_id": "EV-0000000000000001",
        "source_tool": "http_assessor",
        "source_observation_id": "obs-1",
        "observation_type": "web_configuration",
        "host": "localhost",
        "port": 3000,
        "scheme": "http",
        "url": "http://localhost:3000/",
        "path": "/",
        "cve": [],
        "validation_state": "unvalidated",
        "scope_reference": "http://localhost:3000",
        "first_observed": "2026-08-14T00:00:00Z",
        "last_observed": "2026-08-14T00:00:00Z",
        "execution_performed": False,
        "evidence_digest": "sha256:" + "0" * 64,
    })
    record.update(overrides)
    return record


