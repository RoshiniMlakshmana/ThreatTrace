class TestSemanticHints:
    def test_017_same_finding_hint_merges_unmatched_pair(self):
        a = _record(evidence_id="EV-a", evidence_digest="sha256:" + "26" * 32, cwe=None, path="/a")
        b = _record(evidence_id="EV-b", evidence_digest="sha256:" + "27" * 32, cwe=None, path="/b")
        hints = [{"evidence_id_a": "EV-a", "evidence_id_b": "EV-b", "verdict": "same_finding", "rationale": "Same root cause, different observed paths."}]
        result = correlate_bug_bounty_evidence(evidence_records=[a, b], semantic_hints=hints)
        assert result["total_groups"] == 1

    def test_018_different_finding_hint_never_merges(self):
        a = _record(evidence_id="EV-a", evidence_digest="sha256:" + "28" * 32, cwe=None, path="/a")
        b = _record(evidence_id="EV-b", evidence_digest="sha256:" + "29" * 32, cwe=None, path="/b")
        hints = [{"evidence_id_a": "EV-a", "evidence_id_b": "EV-b", "verdict": "different_finding", "rationale": "Unrelated issues."}]
        result = correlate_bug_bounty_evidence(evidence_records=[a, b], semantic_hints=hints)
        assert result["total_groups"] == 2

    def test_019_uncertain_hint_does_not_merge_but_is_surfaced(self):
        a = _record(evidence_id="EV-a", evidence_digest="sha256:" + "2a" * 32, cwe=None, path="/a")
        b = _record(evidence_id="EV-b", evidence_digest="sha256:" + "2b" * 32, cwe=None, path="/b")
        hints = [{"evidence_id_a": "EV-a", "evidence_id_b": "EV-b", "verdict": "uncertain", "rationale": "Might be related, unclear."}]
        result = correlate_bug_bounty_evidence(evidence_records=[a, b], semantic_hints=hints)
        assert result["total_groups"] == 2
        assert len(result["uncertain_correlations"]) == 1
        assert result["uncertain_correlations"][0]["evidence_id_a"] == "EV-a"

    def test_020_hint_cannot_split_already_grouped_pair(self):
        # Deterministic fingerprint grouping wins -- a hint has no
        # split/undo capability at all in this API.
        a = _record(evidence_id="EV-a", evidence_digest="sha256:" + "2c" * 32, cwe="CWE-1", path="/")
        b = _record(evidence_id="EV-b", evidence_digest="sha256:" + "2d" * 32, source_tool="zap", cwe="CWE-1", path="/")
        hints = [{"evidence_id_a": "EV-a", "evidence_id_b": "EV-b", "verdict": "different_finding", "rationale": "Actually unrelated."}]
        result = correlate_bug_bounty_evidence(evidence_records=[a, b], semantic_hints=hints)
        assert result["total_groups"] == 1  # still grouped -- hint cannot un-merge

    def test_021_unknown_evidence_id_in_hint_raises(self):
        a = _record(evidence_id="EV-a", evidence_digest="sha256:" + "2e" * 32)
        hints = [{"evidence_id_a": "EV-a", "evidence_id_b": "EV-nonexistent", "verdict": "same_finding", "rationale": "x"}]
        with pytest.raises(BugBountyFindingCorrelationError):
            correlate_bug_bounty_evidence(evidence_records=[a], semantic_hints=hints)

    def test_022_invalid_verdict_raises(self):
        a = _record(evidence_id="EV-a", evidence_digest="sha256:" + "2f" * 32)
        b = _record(evidence_id="EV-b", evidence_digest="sha256:" + "30" * 32)
        hints = [{"evidence_id_a": "EV-a", "evidence_id_b": "EV-b", "verdict": "definitely_yes", "rationale": "x"}]
        with pytest.raises(BugBountyFindingCorrelationError):
            correlate_bug_bounty_evidence(evidence_records=[a, b], semantic_hints=hints)

    def test_023_blank_rationale_raises(self):
        a = _record(evidence_id="EV-a", evidence_digest="sha256:" + "31" * 32)
        b = _record(evidence_id="EV-b", evidence_digest="sha256:" + "32" * 32)
        hints = [{"evidence_id_a": "EV-a", "evidence_id_b": "EV-b", "verdict": "same_finding", "rationale": "  "}]
        with pytest.raises(BugBountyFindingCorrelationError):
            correlate_bug_bounty_evidence(evidence_records=[a, b], semantic_hints=hints)

    def test_024_no_hints_supplied_is_fine(self):
        a = _record(evidence_id="EV-a", evidence_digest="sha256:" + "33" * 32)
        result = correlate_bug_bounty_evidence(evidence_records=[a])
        assert result["uncertain_correlations"] == []


