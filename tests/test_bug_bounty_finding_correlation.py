class TestFingerprintGrouping:
    def test_003_title_different_same_vulnerability_groups_together(self):
        # The real CSP example from this project's own live validation:
        # http_assessor's "Missing Content-Security-Policy header" vs
        # ZAP's "Content Security Policy (CSP) Header Not Set" -- wildly
        # different titles, same host/port/path/cwe.
        http_finding = _record(
            evidence_id="EV-http", evidence_digest="sha256:" + "3" * 64, source_tool="http_assessor",
            title="Missing Content-Security-Policy header", cwe="CWE-693", vulnerability_class="security_header_misconfiguration",
            technical_severity="medium", confidence="high",
        )
        zap_finding = _record(
            evidence_id="EV-zap", evidence_digest="sha256:" + "4" * 64, source_tool="zap",
            title="Content Security Policy (CSP) Header Not Set", cwe="CWE-693", vulnerability_class=None,
            technical_severity="medium", confidence="high",
        )
        result = correlate_bug_bounty_evidence(evidence_records=[http_finding, zap_finding])
        assert result["total_groups"] == 1
        group = result["groups"][0]
        assert set(group["member_evidence_ids"]) == {"EV-http", "EV-zap"}
        assert group["multi_tool_corroborated"] is True
        assert set(group["source_tools"]) == {"http_assessor", "zap"}

    def test_004_same_title_different_path_stays_separate(self):
        # Real example from this project's own live ZAP run: two
        # "Timestamp Disclosure - Unix" alerts with the same rule_id but
        # different paths must NOT be merged into one finding.
        first = _record(
            evidence_id="EV-t1", evidence_digest="sha256:" + "5" * 64, source_tool="zap",
            title="Timestamp Disclosure - Unix", cwe=None, path="/",
        )
        second = _record(
            evidence_id="EV-t2", evidence_digest="sha256:" + "6" * 64, source_tool="zap",
            title="Timestamp Disclosure - Unix", cwe=None, path="/robots.txt",
        )
        result = correlate_bug_bounty_evidence(evidence_records=[first, second])
        assert result["total_groups"] == 2

    def test_004b_colliding_evidence_id_with_distinct_digest_never_loses_a_member(self):
        # Regression test for a real bug this checkpoint's own live ZAP
        # validation discovered: core.bug_bounty_evidence_normalization
        # can (rarely, legitimately) hand back two distinct records that
        # happen to carry different evidence_id-derivation inputs but --
        # in the specific case being regression-tested here -- the same
        # evidence_id due to normalization's own content-digest design.
        # Correlation must group both as members of the same finding,
        # never silently keep only one.
        same_id_first = _record(
            evidence_id="EV-collide", evidence_digest="sha256:" + "aa" * 32, source_tool="zap",
            title="Timestamp Disclosure - Unix", cwe=None, path="/", sanitized_evidence="first evidence text",
        )
        same_id_second = _record(
            evidence_id="EV-collide", evidence_digest="sha256:" + "bb" * 32, source_tool="zap",
            title="Timestamp Disclosure - Unix", cwe=None, path="/", sanitized_evidence="second, different evidence text",
        )
        result = correlate_bug_bounty_evidence(evidence_records=[same_id_first, same_id_second])
        assert result["total_input_records"] == 2
        assert result["duplicate_evidence_count"] == 0  # digests differ -- not exact duplicates
        assert result["total_groups"] == 1
        assert len(result["groups"][0]["member_evidence_ids"]) == 2

    def test_005_never_deduplicates_on_title_string_alone(self):
        # Same title, different host -- must not group merely on title.
        a = _record(evidence_id="EV-a", evidence_digest="sha256:" + "7" * 64, title="Same Title", host="host-a", cwe="CWE-1")
        b = _record(evidence_id="EV-b", evidence_digest="sha256:" + "8" * 64, title="Same Title", host="host-b", cwe="CWE-1")
        result = correlate_bug_bounty_evidence(evidence_records=[a, b])
        assert result["total_groups"] == 2

    def test_006_open_port_and_missing_csp_are_not_the_same_finding(self):
        port_obs = _record(
            evidence_id="EV-port", evidence_digest="sha256:" + "9" * 64, source_tool="nmap",
            observation_type="service", cwe=None, vulnerability_class=None, path=None, port=3000,
        )
        csp_finding = _record(
            evidence_id="EV-csp", evidence_digest="sha256:" + "a" * 64, source_tool="http_assessor",
            observation_type="web_configuration", cwe="CWE-693", path="/", port=3000,
        )
        result = correlate_bug_bounty_evidence(evidence_records=[port_obs, csp_finding])
        assert result["total_groups"] == 2


