class TestEvidencePreservationAndContract:
    def test_025_every_evidence_source_preserved_in_group(self):
        a = _record(evidence_id="EV-a", evidence_digest="sha256:" + "34" * 32, source_tool="http_assessor", cwe="CWE-1", path="/")
        b = _record(evidence_id="EV-b", evidence_digest="sha256:" + "35" * 32, source_tool="zap", cwe="CWE-1", path="/")
        c = _record(evidence_id="EV-c", evidence_digest="sha256:" + "36" * 32, source_tool="nuclei", cwe="CWE-1", path="/")
        result = correlate_bug_bounty_evidence(evidence_records=[a, b, c])
        group = result["groups"][0]
        assert set(group["member_evidence_ids"]) == {"EV-a", "EV-b", "EV-c"}
        assert set(group["source_tools"]) == {"http_assessor", "nuclei", "zap"}

    def test_026_exact_output_contract_fields(self):
        a = _record(evidence_id="EV-a", evidence_digest="sha256:" + "37" * 32)
        result = correlate_bug_bounty_evidence(evidence_records=[a])
        assert set(result.keys()) == {
            "correlation_version", "groups", "duplicate_evidence_count", "uncertain_correlations",
            "total_input_records", "total_groups", "execution_performed",
        }

    def test_027_execution_performed_always_false(self):
        a = _record(evidence_id="EV-a", evidence_digest="sha256:" + "38" * 32)
        result = correlate_bug_bounty_evidence(evidence_records=[a])
        assert result["execution_performed"] is False

    def test_028_deterministic_given_same_input(self):
        a = _record(evidence_id="EV-a", evidence_digest="sha256:" + "39" * 32)
        b = _record(evidence_id="EV-b", evidence_digest="sha256:" + "3a" * 32, host="other")
        first = correlate_bug_bounty_evidence(evidence_records=[a, b])
        second = correlate_bug_bounty_evidence(evidence_records=[a, b])
        assert first == second

    def test_029_input_never_mutated(self):
        import copy
        records = [_record(evidence_id="EV-a", evidence_digest="sha256:" + "3b" * 32)]
        snapshot = copy.deepcopy(records)
        correlate_bug_bounty_evidence(evidence_records=records)
        assert records == snapshot

    def test_030_empty_input_yields_empty_groups(self):
        result = correlate_bug_bounty_evidence(evidence_records=[])
        assert result["groups"] == []
        assert result["total_groups"] == 0
        assert result["total_input_records"] == 0


