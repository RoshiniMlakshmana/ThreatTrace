def test_004_duplicate_reviewer_and_requester_self_approval_fail_closed():
    # A reviewer who already recorded an approve review may not review again.
    duplicate_envelope = _envelope(
        current_record=_multi_review_record(
            risk_level="high", required_approvals=2, status="partially_approved"
        ),
        existing_reviews=[_review("Reviewer One", "approve")],
        transition_request=_approve_request(reviewed_by="Reviewer One"),
    )
    exit_code_dup, stdout_dup, _stderr_dup = _run(json.dumps(duplicate_envelope))
    assert exit_code_dup == 2
    assert stdout_dup == ""

    # The original requester may never approve their own request.
    self_approval_envelope = _envelope(
        current_record=_multi_review_record(
            risk_level="low", required_approvals=1, status="pending", requested_by="analyst-jane"
        ),
        existing_reviews=[],
        transition_request=_approve_request(reviewed_by="analyst-jane"),
    )
    exit_code_self, stdout_self, _stderr_self = _run(json.dumps(self_approval_envelope))
    assert exit_code_self == 2
    assert stdout_self == ""


def test_005_rejection_from_partially_approved_succeeds_while_terminal_states_reject_further_review():
    reject_envelope = _envelope(
        current_record=_multi_review_record(
            risk_level="high", required_approvals=2, status="partially_approved"
        ),
        existing_reviews=[_review("Reviewer One", "approve")],
        transition_request=_reject_request(reviewed_by="Reviewer Two"),
    )
    exit_code, stdout, stderr = _run(json.dumps(reject_envelope))

    assert exit_code == 0
    assert stderr == ""
    parsed = json.loads(stdout)
    assert parsed["from_status"] == "partially_approved"
    assert parsed["to_status"] == "rejected"
    assert set(parsed["set_fields"].keys()) == {"status", "rejected_by", "rejected_at", "rejection_reason"}

    # A terminal (already-approved) record rejects any further review.
    terminal_envelope = _envelope(
        current_record=_multi_review_record(
            risk_level="low",
            required_approvals=1,
            status="approved",
            approved_by="Security Reviewer",
            approved_at=REVIEW_DECIDED_AT,
        ),
        existing_reviews=[],
        transition_request=_approve_request(reviewed_by="Another Reviewer"),
    )
    exit_code_terminal, stdout_terminal, _stderr_terminal = _run(json.dumps(terminal_envelope))
    assert exit_code_terminal == 2
    assert stdout_terminal == ""


def test_006_malformed_input_fails_safely_inputs_unmodified_and_output_deterministic():
    for raw in ("", "{not valid json", "null", "[]"):
        exit_code, stdout, stderr = _run(raw)
        assert exit_code == 2
        assert stdout == ""
        assert "Traceback" not in stderr

    envelope = _envelope(
        current_record=_multi_review_record(risk_level="low", required_approvals=1, status="pending"),
        existing_reviews=[],
        transition_request=_approve_request(reviewed_by="Security Reviewer"),
    )
    snapshot = copy.deepcopy(envelope)

    exit_code, stdout, _stderr = _run(json.dumps(envelope))

    assert exit_code == 0
    assert envelope == snapshot

    parsed = json.loads(stdout)
    assert list(parsed.keys()) == sorted(parsed.keys())
    round_tripped = json.dumps(parsed, sort_keys=True, ensure_ascii=False) + "\n"
    assert round_tripped == stdout
