class TestConfidenceAggregation:
    def test_012_single_tool_confidence_never_bumped(self):
        record = _record(evidence_id="EV-a", evidence_digest="sha256:" + "1d" * 32, confidence="medium", cwe="CWE-1")
        result = correlate_bug_bounty_evidence(evidence_records=[record])
        assert result["groups"][0]["aggregated_confidence"] == "medium"
        assert result["groups"][0]["multi_tool_corroborated"] is False

    def test_013_multi_tool_corroboration_bumps_confidence_one_level(self):
        a = _record(evidence_id="EV-a", evidence_digest="sha256:" + "1e" * 32, source_tool="http_assessor", confidence="medium", cwe="CWE-1", path="/")
        b = _record(evidence_id="EV-b", evidence_digest="sha256:" + "1f" * 32, source_tool="zap", confidence="medium", cwe="CWE-1", path="/")
        result = correlate_bug_bounty_evidence(evidence_records=[a, b])
        assert result["groups"][0]["aggregated_confidence"] == "high"
        assert result["groups"][0]["corroboration_count"] == 2

    def test_014_confidence_bump_capped_at_high(self):
        a = _record(evidence_id="EV-a", evidence_digest="sha256:" + "20" * 32, source_tool="http_assessor", confidence="high", cwe="CWE-1", path="/")
        b = _record(evidence_id="EV-b", evidence_digest="sha256:" + "21" * 32, source_tool="zap", confidence="high", cwe="CWE-1", path="/")
        result = correlate_bug_bounty_evidence(evidence_records=[a, b])
        assert result["groups"][0]["aggregated_confidence"] == "high"

    def test_015_same_tool_repeated_never_corroborates(self):
        # Two observations from the *same* tool about the same issue --
        # never treated as independent corroboration.
        a = _record(evidence_id="EV-a", evidence_digest="sha256:" + "22" * 32, source_tool="nuclei", confidence=None, cwe="CWE-1", path="/", source_observation_id="t1")
        b = _record(evidence_id="EV-b", evidence_digest="sha256:" + "23" * 32, source_tool="nuclei", confidence=None, cwe="CWE-1", path="/", source_observation_id="t2")
        result = correlate_bug_bounty_evidence(evidence_records=[a, b])
        assert result["groups"][0]["multi_tool_corroborated"] is False
        assert result["groups"][0]["corroboration_count"] == 1

    def test_016_severity_aggregated_as_highest_among_members(self):
        a = _record(evidence_id="EV-a", evidence_digest="sha256:" + "24" * 32, technical_severity="low", cwe="CWE-1", path="/")
        b = _record(evidence_id="EV-b", evidence_digest="sha256:" + "25" * 32, source_tool="zap", technical_severity="high", cwe="CWE-1", path="/")
        result = correlate_bug_bounty_evidence(evidence_records=[a, b])
        assert result["groups"][0]["aggregated_technical_severity"] == "high"


